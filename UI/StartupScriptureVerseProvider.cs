            return string.IsNullOrWhiteSpace(shortReference)
                ? string.Empty
                : $"—— {shortReference} ——";
        }

        internal static string GetShortReference(string reference)
        {
            if (string.IsNullOrWhiteSpace(reference))
            {
                return string.Empty;
            }

            string trimmed = reference.Trim();
            int splitIndex = trimmed.IndexOf(' ');
            if (splitIndex <= 0 || splitIndex >= trimmed.Length - 1)
            {
                return trimmed;
            }

            string bookName = trimmed.Substring(0, splitIndex);
            string location = trimmed.Substring(splitIndex + 1).Trim();
            string shortBookName = BookAbbreviations.TryGetValue(bookName, out string abbreviation)
                ? abbreviation
                : bookName;

            return $"{shortBookName} {location}";
        }

        private static string Format(StartupScriptureVerse verse)
        {
            return $"{verse.Text}（{verse.Reference}）";
        }
    }
