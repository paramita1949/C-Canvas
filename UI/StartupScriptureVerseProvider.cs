            return GetRandomVerseText(Random.Shared);
        }

        internal static string GetRandomVerseText(Random random)
        {
            return Format(GetRandomVerse(random));
        }

        internal static StartupScriptureVerse GetRandomVerse(Random random)
        {
            if (random == null)
            {
                random = Random.Shared;
            }

            return Verses[random.Next(Verses.Length)];
        }

        internal static void SplitDisplayText(string displayText, out string text, out string reference)
        {
            string trimmed = string.IsNullOrWhiteSpace(displayText)
                ? Format(GetRandomVerse(Random.Shared))
                : displayText.Trim();
            int referenceStart = trimmed.LastIndexOf('（');
            bool hasClosingBracket = trimmed.EndsWith("）", StringComparison.Ordinal);

            if (referenceStart > 0 && hasClosingBracket)
            {
                text = trimmed.Substring(0, referenceStart).Trim();
                reference = trimmed.Substring(referenceStart + 1, trimmed.Length - referenceStart - 2).Trim();
                return;
            }

            text = trimmed;
            reference = string.Empty;
        }

